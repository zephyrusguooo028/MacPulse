import Foundation
import Observation

enum ArtifactKind: String {
    case dependency = "依赖"
    case build = "构建产物"
    case cache = "缓存"

    var hint: String {
        switch self {
        case .dependency: return L("重新安装依赖即可恢复（npm install 等）", "Restored by reinstalling dependencies (npm install, etc.)")
        case .build: return L("重新构建即可生成", "Regenerated by rebuilding")
        case .cache: return L("工具缓存，会自动重建", "Tool cache, rebuilt automatically")
        }
    }

    var title: String {
        switch self {
        case .dependency: return L("依赖", "Dependencies")
        case .build: return L("构建产物", "Build output")
        case .cache: return L("缓存", "Cache")
        }
    }
}

struct Artifact: Identifiable, Hashable {
    let url: URL
    let kind: ArtifactKind
    var size: Int64
    /// True when the folder is git-ignored or is unambiguously generated (node_modules…).
    let safe: Bool
    var id: URL { url }
}

struct Project: Identifiable, Hashable {
    let url: URL
    let displayName: String
    let tags: [String]
    var sourceSize: Int64
    var gitSize: Int64
    var artifacts: [Artifact]
    let lastModified: Date?
    var id: URL { url }

    var artifactSize: Int64 { artifacts.reduce(0) { $0 + $1.size } }
    var totalSize: Int64 { sourceSize + gitSize + artifactSize }
    var safeArtifactSize: Int64 { artifacts.filter(\.safe).reduce(0) { $0 + $1.size } }
}

enum ProjectRules {
    static var markers: [(file: String, tag: String)] { [
        ("package.json", "Node"), ("project.config.json", L("小程序", "Mini Program")), ("go.mod", "Go"), ("Cargo.toml", "Rust"),
        ("pyproject.toml", "Python"), ("requirements.txt", "Python"), ("Package.swift", "Swift"),
        ("pom.xml", "Java"), ("build.gradle", "Gradle"), ("build.gradle.kts", "Gradle"),
        ("pubspec.yaml", "Flutter"), ("composer.json", "PHP"), ("Gemfile", "Ruby"), ("CMakeLists.txt", "C/C++"),
    ] }

    /// Folder names that are always generated.
    static let alwaysSafe: [String: ArtifactKind] = [
        "node_modules": .dependency, "miniprogram_npm": .dependency, ".venv": .dependency, "venv": .dependency,
        "Pods": .dependency, ".pnpm-store": .dependency,
        ".next": .build, ".nuxt": .build, ".output": .build, ".svelte-kit": .build, ".angular": .build,
        ".turbo": .cache, ".parcel-cache": .cache, ".vite": .cache, ".cache": .cache, "__pycache__": .cache,
        ".pytest_cache": .cache, ".mypy_cache": .cache, ".gradle": .cache, ".dart_tool": .cache, ".expo": .cache,
        "DerivedData": .build, ".build": .build, "coverage": .build, "storybook-static": .build,
    ]

    /// Names that are usually generated but are sometimes real source; safe only if git-ignored.
    static let maybe: [String: ArtifactKind] = [
        "dist": .build, "build": .build, "out": .build, "target": .build, "unpackage": .build, "release": .build,
    ]

    static let skipWhenSearching: Set<String> = ["node_modules", "Library", "Applications", ".Trash", "Pictures", "Movies", "Music"]
}

final class ProjectScanEngine: @unchecked Sendable {
    private let lock = NSLock()
    private var _cancelled = false
    private var _status = ""
    func cancel() { lock.lock(); _cancelled = true; lock.unlock() }
    var cancelled: Bool { lock.lock(); defer { lock.unlock() }; return _cancelled }
    var status: String { lock.lock(); defer { lock.unlock() }; return _status }
    private func setStatus(_ s: String) { lock.lock(); _status = s; lock.unlock() }

    func findProjects(roots: [URL]) -> [(URL, [String], URL)] {
        var found: [(URL, [String], URL)] = []
        for r in roots { search(r, root: r, depth: 0, into: &found) }
        return found
    }

    private func search(_ dir: URL, root: URL, depth: Int, into found: inout [(URL, [String], URL)]) {
        if cancelled || depth > 4 { return }
        let fm = FileManager.default
        guard let names = try? fm.contentsOfDirectory(atPath: dir.path) else { return }
        let set = Set(names)
        var tags = ProjectRules.markers.filter { set.contains($0.file) }.map(\.tag)
        if set.contains(".git") { tags.append("Git") }
        if !tags.isEmpty, dir != root {
            var seen = Set<String>()
            found.append((dir, tags.filter { seen.insert($0).inserted }, root))
            return
        }
        for n in names where !n.hasPrefix(".") && !ProjectRules.skipWhenSearching.contains(n) {
            let u = dir.appendingPathComponent(n)
            var isDir: ObjCBool = false
            guard fm.fileExists(atPath: u.path, isDirectory: &isDir), isDir.boolValue else { continue }
            if (try? u.resourceValues(forKeys: [.isSymbolicLinkKey, .isPackageKey])).map({ $0.isSymbolicLink == true || $0.isPackage == true }) == true { continue }
            search(u, root: root, depth: depth + 1, into: &found)
        }
    }

    func measure(_ url: URL, tags: [String], root: URL) -> Project {
        setStatus(url.lastPathComponent)
        let ignored = Self.gitignoreNames(url)
        var artifacts: [Artifact] = []
        var source: Int64 = 0
        var gitSize: Int64 = 0
        var latest: Date?

        let keys: [URLResourceKey] = [.isDirectoryKey, .isSymbolicLinkKey, .totalFileAllocatedSizeKey, .fileAllocatedSizeKey, .contentModificationDateKey]
        let fm = FileManager.default
        guard let e = fm.enumerator(at: url, includingPropertiesForKeys: keys, options: [], errorHandler: { _, _ in true }) else {
            return Project(url: url, displayName: url.lastPathComponent, tags: tags, sourceSize: 0, gitSize: 0, artifacts: [], lastModified: nil)
        }
        for case let f as URL in e {
            if cancelled { break }
            guard let v = try? f.resourceValues(forKeys: Set(keys)) else { continue }
            if v.isSymbolicLink == true { continue }
            let name = f.lastPathComponent
            if v.isDirectory == true {
                if name == ".git" && f.deletingLastPathComponent() == url {
                    gitSize = FileSizer.size(of: f)
                    e.skipDescendants()
                    continue
                }
                if let kind = ProjectRules.alwaysSafe[name] {
                    artifacts.append(Artifact(url: f, kind: kind, size: FileSizer.size(of: f), safe: true))
                    e.skipDescendants()
                    continue
                }
                if let kind = ProjectRules.maybe[name] {
                    let safe = ignored.contains(name) || Self.gitignoreNames(f.deletingLastPathComponent()).contains(name)
                    artifacts.append(Artifact(url: f, kind: kind, size: FileSizer.size(of: f), safe: safe))
                    e.skipDescendants()
                    continue
                }
                continue
            }
            source += Int64(v.totalFileAllocatedSize ?? v.fileAllocatedSize ?? 0)
            if let m = v.contentModificationDate, latest.map({ m > $0 }) ?? true { latest = m }
        }

        let rel = url.path.replacingOccurrences(of: root.path + "/", with: "")
        let display = rel.split(separator: "/").joined(separator: " › ")
        return Project(url: url, displayName: display.isEmpty ? url.lastPathComponent : display, tags: tags,
                       sourceSize: source, gitSize: gitSize, artifacts: artifacts.sorted { $0.size > $1.size },
                       lastModified: latest)
    }

    /// Plain folder names listed in a .gitignore ("dist", "/dist", "dist/").
    static func gitignoreNames(_ dir: URL) -> Set<String> {
        guard let s = try? String(contentsOf: dir.appendingPathComponent(".gitignore"), encoding: .utf8) else { return [] }
        var out = Set<String>()
        for raw in s.split(whereSeparator: \.isNewline) {
            var l = raw.trimmingCharacters(in: .whitespaces)
            if l.isEmpty || l.hasPrefix("#") || l.hasPrefix("!") { continue }
            if l.hasPrefix("/") { l.removeFirst() }
            if l.hasSuffix("/") { l.removeLast() }
            if l.hasPrefix("**/") { l.removeFirst(3) }
            if !l.contains("/") && !l.contains("*") { out.insert(l) }
        }
        return out
    }
}

@MainActor
@Observable
final class ProjectModel {
    var projects: [Project] = []
    var scanning = false
    var status = ""
    var lastScan: Date?
    @ObservationIgnored private var engine: ProjectScanEngine?

    var totalArtifacts: Int64 { projects.reduce(0) { $0 + $1.artifactSize } }
    var safeArtifacts: Int64 { projects.reduce(0) { $0 + $1.safeArtifactSize } }

    func scan() {
        engine?.cancel()
        let engine = ProjectScanEngine()
        self.engine = engine
        scanning = true
        status = L("查找项目…", "Finding projects…")
        let roots = AppSettings.shared.projectRootURLs
        Task.detached(priority: .utility) {
            let found = engine.findProjects(roots: roots)
            await MainActor.run { self.status = L("找到 \(found.count) 个项目，正在计算大小…", "Found \(found.count) projects, calculating sizes…") }
            let results = UnsafeMutableBufferPointer<Project?>.allocate(capacity: found.count)
            results.initialize(repeating: nil)
            DispatchQueue.concurrentPerform(iterations: found.count) { i in
                let (u, tags, root) = found[i]
                results[i] = engine.measure(u, tags: tags, root: root)
            }
            let list = results.compactMap { $0 }.sorted { $0.totalSize > $1.totalSize }
            results.deallocate()
            await MainActor.run {
                guard self.engine === engine else { return }
                self.projects = list
                self.scanning = false
                self.status = ""
                self.lastScan = Date()
            }
        }
    }

    func removed(_ urls: Set<URL>) {
        for i in projects.indices {
            projects[i].artifacts.removeAll { urls.contains($0.url) }
        }
    }
}
