// MARK: - Model

enum ClipKind: String, Codable, CaseIterable {
    case text, link, image, file

    var title: String {
        switch self {
        case .text: return L("文本", "Text")
        case .link: return L("链接", "Links")
        case .image: return L("图片", "Images")
        case .file: return L("文件", "Files")
        }
    }

    var symbol: String {
        switch self {
        case .text: return "text.alignleft"
        case .link: return "link"
        case .image: return "photo"
        case .file: return "doc"
        }
    }
}

struct ClipItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var kind: ClipKind
    /// Text or link content.
    var text: String?
    /// PNG file name inside the clipboard folder (or "demo:N" in demo mode).
    var image: String?
    var imageWidth: Int?
    var imageHeight: Int?
    var paths: [String]?
    var source: String?
    var date = Date()
    var pinned = false
    /// De-duplication key.
    var key: String

    /// One-line preview for lists.
    var preview: String {
        switch kind {
        case .text, .link:
            let t = (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
            return String(t.prefix(400)).replacingOccurrences(of: "\n", with: " ⏎ ")
        case .image:
            if let w = imageWidth, let h = imageHeight { return L("图片 \(w) × \(h)", "Image \(w) × \(h)") }
            return L("图片", "Image")
        case .file:
            let p = paths ?? []
            let first = p.first.map { ($0 as NSString).lastPathComponent } ?? ""
            return p.count > 1 ? L("\(first) 等 \(p.count) 个文件", "\(first) and \(p.count - 1) more") : first
        }
    }

    func matches(_ q: String) -> Bool {
        if q.isEmpty { return true }
        if (text ?? "").localizedCaseInsensitiveContains(q) { return true }
        if (source ?? "").localizedCaseInsensitiveContains(q) { return true }
        if (paths ?? []).contains(where: { $0.localizedCaseInsensitiveContains(q) }) { return true }
        return preview.localizedCaseInsensitiveContains(q)
    }
}

// MARK: - Store

/// Clipboard history: polls the general pasteboard, keeps an index in
/// `Paths.support/clipboard/index.json` and images as PNG files next to it.
/// Nothing ever leaves the Mac.
@MainActor
@Observable
final class ClipboardStore {
    static let shared = ClipboardStore()

    static let defaultHotkey = HotkeySpec(keyCode: UInt32(kVK_ANSI_V), modifiers: UInt32(optionKey | shiftKey), label: "V")
    static let internalType = NSPasteboard.PasteboardType("app.peekaboo.internal")
    /// Password managers and other apps mark secret or throwaway content with these (nspasteboard.org).
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping", "net.antelle.keeweb",
    ]
    private static let hotkeyID: UInt32 = 2
    private static let maxImageBytes = 40 * 1_048_576
    private static let maxTextChars = 1_000_000

    private let d = UserDefaults.standard

    var items: [ClipItem] = []
    var enabled: Bool { didSet { d.set(enabled, forKey: "clipboard.enabled"); apply() } }
    var maxItems: Int { didSet { d.set(maxItems, forKey: "clipboard.maxItems"); evict(); save() } }
    var autoPaste: Bool { didSet { d.set(autoPaste, forKey: "clipboard.autoPaste") } }
    /// nil = no shortcut.
    var hotkey: HotkeySpec? { didSet { d.set(try? JSONEncoder().encode(hotkey), forKey: "clipboard.hotkeySpec"); applyHotkey() } }
    private(set) var hotkeyOK = true

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var loaded = false
    @ObservationIgnored private let thumbs = NSCache<NSString, NSImage>()

    var folder: URL {
        let u = Paths.support.appendingPathComponent("clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: u, withIntermediateDirectories: true)
        return u
    }
    private var indexURL: URL { folder.appendingPathComponent("index.json") }

    private init() {
        enabled = d.object(forKey: "clipboard.enabled") as? Bool ?? true
        maxItems = d.object(forKey: "clipboard.maxItems") as? Int ?? 200
        autoPaste = d.object(forKey: "clipboard.autoPaste") as? Bool ?? false
        if let data = d.data(forKey: "clipboard.hotkeySpec") {
            hotkey = (try? JSONDecoder().decode(HotkeySpec?.self, from: data)) ?? nil
        } else {
            hotkey = Self.defaultHotkey
        }
    }

    // MARK: Lifecycle

    func apply() {
        if !loaded { load() }
        if enabled && !Demo.active {
            if timer == nil {
                lastChange = NSPasteboard.general.changeCount   // don't import whatever was there before launch
                let t = Timer(timeInterval: 0.5, repeats: true) { _ in MainActor.assumeIsolated { ClipboardStore.shared.poll() } }
                RunLoop.main.add(t, forMode: .common)
                timer = t
            }
        } else {
            timer?.invalidate()
            timer = nil
        }
        applyHotkey()
    }

    func applyHotkey() {
        // Demo runs sit beside the real app; don't steal its shortcut.
        if enabled, !Demo.active, let k = hotkey {
            hotkeyOK = Hotkeys.shared.register(id: Self.hotkeyID, keyCode: k.keyCode, modifiers: k.modifiers) { ClipboardPicker.shared.toggle() }
        } else {
            Hotkeys.shared.unregister(id: Self.hotkeyID)
            hotkeyOK = true
        }
    }

    private func load() {
        loaded = true
        if Demo.active { items = ClipboardDemo.items(); return }
        guard let data = try? Data(contentsOf: indexURL) else { return }
        let dec = JSONDecoder()
        dec.dateDecodingStrategy = .secondsSince1970
        items = (try? dec.decode([ClipItem].self, from: data)) ?? []
    }

    private func save() {
        guard loaded, !Demo.active else { return }
        let enc = JSONEncoder()
        enc.dateEncodingStrategy = .secondsSince1970
        guard let data = try? enc.encode(items) else { return }
        let url = indexURL
        DispatchQueue.global(qos: .utility).async { try? data.write(to: url, options: .atomic) }
    }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChange else { return }
        lastChange = count
        let types = Set((pb.types ?? []).map(\.rawValue))
        if types.isEmpty || types.contains(Self.internalType.rawValue) || !types.isDisjoint(with: Self.skippedTypes) { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        // Files first: Finder also puts the file name as text and the icon as an image.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            add(ClipItem(kind: .file, paths: paths, source: source, key: "f:" + paths.joined(separator: "\n")))
            return
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard s.count <= Self.maxTextChars else { return }
            add(ClipItem(kind: Self.isLink(s) ? .link : .text, text: s, source: source, key: "t:" + s))
            return
        }
        if let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff), raw.count <= Self.maxImageBytes {
            let isPNG = pb.data(forType: .png) != nil
            let folder = self.folder
            Task.detached(priority: .utility) {
                let key = "i:" + SHA256.hash(data: raw).map { String(format: "%02x", $0) }.joined()
                let converted = isPNG ? raw : NSBitmapImageRep(data: raw)?.representation(using: .png, properties: [:])
                guard let png = converted, let rep = NSBitmapImageRep(data: png) else { return }
                let (w, h) = (rep.pixelsWide, rep.pixelsHigh)
                let name = UUID().uuidString + ".png"
                await MainActor.run {
                    let store = ClipboardStore.shared
                    if let i = store.items.firstIndex(where: { $0.key == key }) { store.bump(i, source: source); return }
                    guard (try? png.write(to: folder.appendingPathComponent(name))) != nil else { return }
                    store.add(ClipItem(kind: .image, image: name, imageWidth: w, imageHeight: h, source: source, key: key))
                }
            }
        }
    }

    static func isLink(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(where: \.isWhitespace), let u = URL(string: t), let scheme = u.scheme?.lowercased() else { return false }
        return ["http", "https", "ftp", "mailto"].contains(scheme) && (u.host != nil || scheme == "mailto")
    }

    private func add(_ item: ClipItem) {
        if let i = items.firstIndex(where: { $0.key == item.key }) { bump(i, source: item.source); return }
        items.insert(item, at: 0)
        evict()
        save()
    }

    /// Re-copied: move to the top.
    private func bump(_ i: Int, source: String?) {
        var it = items.remove(at: i)
        it.date = Date()
        if let source { it.source = source }
        items.insert(it, at: 0)
        save()
    }

    private func evict() {
        while items.count > maxItems, let i = items.lastIndex(where: { !$0.pinned }) {
            deleteFile(of: items[i])
            items.remove(at: i)
        }
    }

    // MARK: Actions

    /// Puts an item back on the pasteboard (marked as Peekaboo's own) and moves it to the top.
    @discardableResult
    func copy(_ item: ClipItem) -> Bool {
        let pb = NSPasteboard.general
        var objects: [NSPasteboardItem] = []
        switch item.kind {
        case .text, .link:
            let p = NSPasteboardItem()
            p.setString(item.text ?? "", forType: .string)
            if item.kind == .link { p.setString(item.text?.trimmingCharacters(in: .whitespacesAndNewlines) ?? "", forType: .URL) }
            objects = [p]
        case .image:
            guard let img = fullImage(item), let tiff = img.tiffRepresentation else { return false }
            let p = NSPasteboardItem()
            if let name = item.image, !name.hasPrefix("demo:"), let png = try? Data(contentsOf: folder.appendingPathComponent(name)) {
                p.setData(png, forType: .png)
            }
            p.setData(tiff, forType: .tiff)
            objects = [p]
        case .file:
            objects = (item.paths ?? []).map { path in
                let p = NSPasteboardItem()
                p.setString(URL(fileURLWithPath: path).absoluteString, forType: .fileURL)
                return p
            }
            if let first = objects.first, let path = item.paths?.first { first.setString(path, forType: .string) }
        }
        guard !objects.isEmpty else { return false }
        for o in objects { o.setData(Data(), forType: Self.internalType) }
        pb.clearContents()
        let ok = pb.writeObjects(objects)
        lastChange = pb.changeCount
        if let i = items.firstIndex(where: { $0.id == item.id }) { bump(i, source: nil) }
        return ok
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        deleteFile(of: items[i])
        items.remove(at: i)
        save()
    }

    /// Removes everything except pinned items.
    func clearUnpinned() {
        for it in items where !it.pinned { deleteFile(of: it) }
        items.removeAll { !$0.pinned }
        save()
    }

    @MainActor
    func confirmClear() {
        let n = items.filter { !$0.pinned }.count
        guard n > 0 else { return }
        if FileActions.confirm(L("清空剪贴板历史？", "Clear clipboard history?"),
                               L("将删除 \(n) 条记录，已固定的条目会保留。此操作无法撤销。", "\(n) items will be deleted. Pinned items are kept. This can't be undone."),
                               ok: L("清空", "Clear")) {
            clearUnpinned()
        }
    }

    private func deleteFile(of item: ClipItem) {
        guard let name = item.image, !name.hasPrefix("demo:") else { return }
        thumbs.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: folder.appendingPathComponent(name))
    }

    // MARK: Images

    func fullImage(_ item: ClipItem) -> NSImage? {
        guard let name = item.image else { return nil }
        if name.hasPrefix("demo:") { return ClipboardDemo.image(name) }
        return NSImage(contentsOf: folder.appendingPathComponent(name))
    }

    /// Small, cached thumbnail (decoded with ImageIO so big screenshots stay cheap).
    func thumbnail(_ item: ClipItem) -> NSImage? {
        guard let name = item.image else { return nil }
        if let t = thumbs.object(forKey: name as NSString) { return t }
        var img: NSImage?
        if name.hasPrefix("demo:") {
            img = ClipboardDemo.image(name)
        } else if let src = CGImageSourceCreateWithURL(folder.appendingPathComponent(name) as CFURL, nil),
                  let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                                                        kCGImageSourceThumbnailMaxPixelSize: 240,
                                                                        kCGImageSourceCreateThumbnailWithTransform: true] as CFDictionary) {
            img = NSImage(cgImage: cg, size: NSSize(width: cg.width, height: cg.height))
        }
        if let img { thumbs.setObject(img, forKey: name as NSString) }
        return img
    }

    // MARK: Auto-paste

    var canAutoPaste: Bool { AXIsProcessTrusted() }

    func requestAccessibility() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }

    /// Sends ⌘V to the frontmost app. Needs Accessibility permission.
    func pasteIntoFrontApp() {
        guard AXIsProcessTrusted() else { return }
        let src = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}

/// Entry point called at launch.
enum ClipboardService {
    @MainActor static func startIfEnabled() { ClipboardStore.shared.apply() }
}

// MARK: - Demo data

/// Made-up items for `--demo`, so screenshots never contain anyone's clipboard.
enum ClipboardDemo {
    @MainActor
    static func items() -> [ClipItem] {
        func ago(_ m: Double) -> Date { Date().addingTimeInterval(-60 * m) }
        return [
            ClipItem(kind: .text, text: L("周五下午 3 点在 2 号会议室开产品评审会，记得带上新版原型。", "Product review on Friday at 3 pm in room 2. Please bring the new prototype."), source: "Notes", date: ago(1), key: "t:d1"),
            ClipItem(kind: .link, text: "https://github.com/peekaboo-app/peekaboo", source: "Safari", date: ago(4), pinned: true, key: "t:d2"),
            ClipItem(kind: .image, image: "demo:0", imageWidth: 1280, imageHeight: 800, source: "Peekaboo", date: ago(9), key: "i:d3"),
            ClipItem(kind: .text, text: "func greet(_ name: String) -> String {\n    \"Hello, \\(name)!\"\n}", source: "Xcode", date: ago(18), key: "t:d4"),
            ClipItem(kind: .file, paths: [Paths.h("Documents/Quarterly Report.pdf").path, Paths.h("Documents/Budget 2026.xlsx").path], source: "Finder", date: ago(35), key: "f:d5"),
            ClipItem(kind: .text, text: L("北京市海淀区中关村大街 1 号", "1 Infinite Loop, Cupertino, CA"), source: "Maps", date: ago(62), pinned: true, key: "t:d6"),
            ClipItem(kind: .image, image: "demo:1", imageWidth: 640, imageHeight: 480, source: "Preview", date: ago(130), key: "i:d7"),
            ClipItem(kind: .link, text: "https://developer.apple.com/documentation/vision", source: "Safari", date: ago(240), key: "t:d8"),
            ClipItem(kind: .text, text: "brew install --cask peekaboo", source: "Terminal", date: ago(60 * 26), key: "t:d9"),
        ]
    }

    private static var cache: [String: NSImage] = [:]

    static func image(_ name: String) -> NSImage {
        if let i = cache[name] { return i }
        let second = name == "demo:1"
        let size = second ? NSSize(width: 320, height: 240) : NSSize(width: 320, height: 200)
        let img = NSImage(size: size, flipped: false) { r in
            let colors = second ? [NSColor.systemOrange, NSColor.systemPink] : [NSColor.systemBlue, NSColor.systemTeal]
            NSGradient(colors: colors)?.draw(in: r, angle: 35)
            NSColor.white.withAlphaComponent(0.85).setFill()
            if second {
                NSBezierPath(ovalIn: NSRect(x: 110, y: 70, width: 100, height: 100)).fill()
            } else {
                NSBezierPath(roundedRect: NSRect(x: 30, y: 30, width: 260, height: 140), xRadius: 10, yRadius: 10).fill()
                NSColor.systemBlue.withAlphaComponent(0.6).setFill()
                for k in 0..<4 { NSRect(x: 50, y: 140 - CGFloat(k) * 26, width: CGFloat(200 - k * 30), height: 10).fill() }
            }
            return true
        }
        cache[name] = img
        return img
    }
}
